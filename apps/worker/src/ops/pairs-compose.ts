/**
 * Renders the per-pair worker services for production (infra/prod/compose.pairs.yaml).
 *
 * One process (container) per pair: a crash, a stuck feed or a memory leak in one pair never
 * touches the others, and each keeps the proven single-pair worker unchanged. The dead-man sidecar
 * is rendered here too, because it must know exactly which workers are expected.
 */
export interface PairSpec {
  symbol: string;
  reference: string;
}

export interface PairsFile {
  /** The scan this selection came from (pre-registration). */
  scan: { file: string; paramsHash: string; startedAt: string };
  pairs: PairSpec[];
}

const SYMBOL = /^[A-Z0-9]{4,20}$/;

export function validatePairs(f: PairsFile): void {
  if (f.pairs.length === 0) throw new Error('no pairs selected');
  const seen = new Set<string>();
  for (const p of f.pairs) {
    if (!SYMBOL.test(p.symbol) || !SYMBOL.test(p.reference)) throw new Error(`invalid symbol ${p.symbol}/${p.reference}`);
    if (seen.has(p.symbol)) throw new Error(`duplicate pair ${p.symbol}`);
    seen.add(p.symbol);
  }
  if (!/^[0-9a-f]{64}$/.test(f.scan.paramsHash)) throw new Error('scan.paramsHash must be a sha256 hex');
}

export const IMAGE = 'ghcr.io/andr3wgustavo/cortex-worker';

export function renderPairsCompose(f: PairsFile): string {
  validatePairs(f);
  const svc = (p: PairSpec) => `  worker-${p.symbol.toLowerCase()}:
    <<: *worker
    container_name: cortex-worker-${p.symbol.toLowerCase()}
    environment:
      <<: *worker-env
      BOT_SYMBOL: ${p.symbol}
      BOT_REFERENCE_SYMBOL: ${p.reference}
`;
  return `# GENERATED by apps/worker/src/ops/pairs-cli.ts from infra/prod/pairs.json — do not edit by hand.
# Pre-registered selection: scan ${f.scan.file} (params ${f.scan.paramsHash.slice(0, 12)}, ${f.scan.startedAt}).
# Use together with compose.prod.yaml:
#   docker compose --env-file /srv/cortex/cortex.env -f compose.prod.yaml -f compose.pairs.yaml up -d --wait

x-worker-env: &worker-env
  TRADING_MODE: shadow
  LOG_LEVEL: \${LOG_LEVEL:-info}
  APP_VERSION: \${IMAGE_TAG:?set IMAGE_TAG}
  DATABASE_URL: postgresql://cortex:\${POSTGRES_PASSWORD:?set POSTGRES_PASSWORD}@postgres:5432/farm_shadow?connection_limit=3
  REDIS_URL: redis://redis:6379
  PERSIST_ENABLED: "true"
  MARKET_DATA_DIR: /data/market
  HEARTBEAT_DIR: /data/health
  SHADOW_START_QUOTE: "15"

x-worker: &worker
  image: ${IMAGE}:\${IMAGE_TAG:?set IMAGE_TAG}
  restart: unless-stopped
  # SIGTERM → drain (stop feeds, close recording, final snapshot); the worker hard-exits at 15 s.
  stop_grace_period: 30s
  mem_limit: 384m
  volumes:
    - \${CORTEX_DATA:-/srv/cortex/data}:/data
  depends_on:
    postgres: { condition: service_healthy }
    redis: { condition: service_healthy }
  healthcheck:
    # Healthy = fresh heartbeat from THIS image version with a live MEXC feed (deploy smoke test).
    test: ["CMD", "node", "dist/healthcheck.js"]
    interval: 15s
    timeout: 5s
    retries: 4
    start_period: 120s
  logging:
    driver: json-file
    options: { max-size: 20m, max-file: "5" }

services:
${f.pairs.map(svc).join('\n')}
  deadman:
    image: ${IMAGE}:\${IMAGE_TAG:?set IMAGE_TAG}
    container_name: cortex-deadman
    restart: unless-stopped
    command: ["node", "dist/deadman.js"]
    mem_limit: 96m
    environment:
      HEARTBEAT_DIR: /data/health
      EXPECTED_BOTS: ${f.pairs.map((p) => p.symbol).join(',')}
      HEALTHCHECK_URL: \${HEALTHCHECK_URL:-}
    volumes:
      - \${CORTEX_DATA:-/srv/cortex/data}:/data:ro
    logging:
      driver: json-file
      options: { max-size: 5m, max-file: "3" }
`;
}
